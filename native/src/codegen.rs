use std::collections::HashMap;
use std::fmt;

use crate::parser::{Expr, Function, Program, Statement, Type};

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CompileError {
    pub line: usize,
    pub message: String,
}

impl CompileError {
    pub fn new(line: usize, message: impl Into<String>) -> Self {
        Self {
            line,
            message: message.into(),
        }
    }
}

impl fmt::Display for CompileError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "السطر {}: {}", self.line, self.message)
    }
}

impl std::error::Error for CompileError {}

pub fn emit_rust(program: &Program) -> Result<String, CompileError> {
    let functions: HashMap<_, _> = program
        .functions
        .iter()
        .enumerate()
        .map(|(index, function)| (function.name.clone(), format!("__suda_fn_{index}")))
        .collect();
    let mut output = String::from("// Generated by the Rust-native Suda compiler.\n");
    for (index, function) in program.functions.iter().enumerate() {
        emit_function(function, index, &functions, &mut output)?;
    }
    let entry = program
        .functions
        .iter()
        .position(|function| function.name == "رئيسية")
        .ok_or_else(|| CompileError::new(1, "الدالة «رئيسية» مطلوبة."))?;
    output.push_str(&format!(
        "\npub fn suda_entry() {{ __suda_fn_{entry}(); }}\n"
    ));
    output.push_str("fn main() { suda_entry(); }\n");
    Ok(output)
}

fn emit_function(
    function: &Function,
    index: usize,
    functions: &HashMap<String, String>,
    output: &mut String,
) -> Result<(), CompileError> {
    let mut generator = Generator {
        functions,
        scopes: vec![HashMap::new()],
        next_variable: 0,
    };
    let mut parameters = Vec::with_capacity(function.parameters.len());
    for parameter in &function.parameters {
        let generated = generator.fresh_variable();
        generator
            .scopes
            .last_mut()
            .expect("function scope exists")
            .insert(
                parameter.name.clone(),
                (generated.clone(), parameter.ty.clone()),
            );
        parameters.push(format!("{generated}: {}", parameter.ty.rust_name()));
    }
    output.push_str(&format!(
        "\n#[allow(unused_variables, unused_mut)]\npub fn __suda_fn_{index}({}) -> {} {{\n",
        parameters.join(", "),
        function.result.rust_name()
    ));
    generator.emit_statements(&function.body, output)?;
    output.push_str("}\n");
    Ok(())
}

struct Generator<'a> {
    functions: &'a HashMap<String, String>,
    scopes: Vec<HashMap<String, (String, Type)>>,
    next_variable: usize,
}

impl Generator<'_> {
    fn fresh_variable(&mut self) -> String {
        let name = format!("__suda_v{}", self.next_variable);
        self.next_variable += 1;
        name
    }

    fn emit_statements(
        &mut self,
        statements: &[Statement],
        output: &mut String,
    ) -> Result<(), CompileError> {
        for statement in statements {
            match statement {
                Statement::Let {
                    name, ty, value, ..
                } => {
                    let value = self.expression(value)?;
                    let generated = self.fresh_variable();
                    self.scopes
                        .last_mut()
                        .expect("function scope exists")
                        .insert(name.clone(), (generated.clone(), ty.clone()));
                    output.push_str(&format!(
                        "let mut {generated}: {} = {value};\n",
                        ty.rust_name()
                    ));
                }
                Statement::Assign { name, value, line } => {
                    let generated = self.variable(name, *line)?;
                    output.push_str(&format!("{generated} = {};\n", self.expression(value)?));
                }
                Statement::Return { value, .. } => {
                    if let Some(value) = value {
                        output.push_str(&format!("return {};\n", self.expression(value)?));
                    } else {
                        output.push_str("return;\n");
                    }
                }
                Statement::Expression { value, .. } => {
                    output.push_str(&format!("{};\n", self.expression(value)?));
                }
                Statement::If {
                    condition, yes, no, ..
                } => {
                    output.push_str(&format!("if {} {{\n", self.expression(condition)?));
                    self.emit_nested(yes, output)?;
                    if no.is_empty() {
                        output.push_str("}\n");
                    } else {
                        output.push_str("} else {\n");
                        self.emit_nested(no, output)?;
                        output.push_str("}\n");
                    }
                }
                Statement::While {
                    condition, body, ..
                } => {
                    output.push_str(&format!("while {} {{\n", self.expression(condition)?));
                    self.emit_nested(body, output)?;
                    output.push_str("}\n");
                }
                Statement::CountedLoop {
                    name,
                    start,
                    end,
                    body,
                    ..
                } => {
                    let generated = self.fresh_variable();
                    output.push_str(&format!(
                        "for mut {generated} in {}..{} {{\n",
                        self.expression(start)?,
                        self.expression(end)?
                    ));
                    self.scopes
                        .push(HashMap::from([(name.clone(), (generated, Type::I64))]));
                    self.emit_statements(body, output)?;
                    self.scopes.pop();
                    output.push_str("}\n");
                }
            }
        }
        Ok(())
    }

    fn emit_nested(
        &mut self,
        statements: &[Statement],
        output: &mut String,
    ) -> Result<(), CompileError> {
        self.scopes.push(HashMap::new());
        let result = self.emit_statements(statements, output);
        self.scopes.pop();
        result
    }

    fn expression(&self, expression: &Expr) -> Result<String, CompileError> {
        let line = expression.line();
        Ok(match expression {
            Expr::Integer(value, _) => value.to_string(),
            Expr::Boolean(value, _) => value.to_string(),
            Expr::Text(value, _) => format!("String::from({value:?})"),
            Expr::Variable(name, _) => {
                let (generated, ty) = self.lookup(name, line)?;
                if ty == Type::Text {
                    format!("{generated}.clone()")
                } else {
                    generated
                }
            }
            Expr::Call(name, arguments, _) if name == "اطبع" => {
                format!("println!(\"{{}}\", {})", self.expression(&arguments[0])?)
            }
            Expr::Call(name, arguments, _) => {
                let function = self
                    .functions
                    .get(name)
                    .ok_or_else(|| CompileError::new(line, format!("دالة غير معرّفة «{name}».")))?;
                let arguments = arguments
                    .iter()
                    .map(|argument| self.expression(argument))
                    .collect::<Result<Vec<_>, _>>()?;
                format!("{function}({})", arguments.join(", "))
            }
            Expr::Unary(operator, operand, _) => {
                let operand = self.expression(operand)?;
                match operator.as_str() {
                    "-" => format!("({operand}).checked_neg().expect(\"Suda integer overflow\")"),
                    "+" => format!("({operand})"),
                    "ليس" => format!("(!{operand})"),
                    _ => return Err(CompileError::new(line, "عامل أحادي غير معروف.")),
                }
            }
            Expr::Binary(operator, left, right, _) => {
                let left = self.expression(left)?;
                let right = self.expression(right)?;
                match operator.as_str() {
                    "+" => checked_binary(&left, &right, "add"),
                    "-" => checked_binary(&left, &right, "sub"),
                    "*" => checked_binary(&left, &right, "mul"),
                    "/" => checked_binary(&left, &right, "div"),
                    "%" => checked_binary(&left, &right, "rem"),
                    "و" => format!("({left} && {right})"),
                    "أو" => format!("({left} || {right})"),
                    "==" | "!=" | "<" | "<=" | ">" | ">=" => {
                        format!("({left} {operator} {right})")
                    }
                    _ => return Err(CompileError::new(line, "عامل ثنائي غير معروف.")),
                }
            }
        })
    }

    fn variable(&self, name: &str, line: usize) -> Result<String, CompileError> {
        self.lookup(name, line).map(|(generated, _)| generated)
    }

    fn lookup(&self, name: &str, line: usize) -> Result<(String, Type), CompileError> {
        self.scopes
            .iter()
            .rev()
            .find_map(|scope| scope.get(name).cloned())
            .ok_or_else(|| CompileError::new(line, format!("اسم غير معرّف «{name}».")))
    }
}

fn checked_binary(left: &str, right: &str, operation: &str) -> String {
    format!("({left}).checked_{operation}({right}).expect(\"Suda arithmetic error\")")
}
